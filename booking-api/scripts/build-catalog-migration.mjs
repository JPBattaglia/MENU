// Builds migrations/0001_subscription_catalog.sql from subscription-catalog.json (stage 3).
// The catalog file stays the single source of prices and Stripe IDs; this turns it into offers,
// offer_versions and workflow_definitions rows. Run: node booking-api/scripts/build-catalog-migration.mjs
// The migration is additive (INSERT only) and is applied once to menu-made-db.
import { readFileSync, writeFileSync } from "node:fs";

const here = new URL("../", import.meta.url);
const catalog = JSON.parse(readFileSync(new URL("subscription-catalog.json", here), "utf8"));
const CREATED = "2026-10-25T00:00:00.000Z";

// Category, approval default (stage 4 refines per step), workflow key and order on the site.
const PLAN_META = {
  REVIEW_REPLIES: { category: "VISIBILITY", approval: 0, workflow: "REVIEW_REPLIES_V1", sort: 20, slug: "review-replies" },
  MENU_CARE: { category: "MENU", approval: 1, workflow: "MENU_CARE_V1", sort: 21, slug: "menu-care" },
  GOOGLE_PROFILE_CARE: { category: "VISIBILITY", approval: 0, workflow: "GOOGLE_PROFILE_CARE_V1", sort: 22, slug: "google-profile-care" },
  SOCIAL_POSTS: { category: "DESIGN", approval: 1, workflow: "SOCIAL_POSTS_V1", sort: 23, slug: "social-posts" },
  WEBSITE_CARE: { category: "WEBSITE", approval: 1, workflow: "WEBSITE_CARE_V1", sort: 24, slug: "website-care" },
  ACCESSIBILITY_MONITORING: { category: "ACCESSIBILITY", approval: 0, workflow: "ACCESSIBILITY_MONITORING_V1", sort: 25, slug: "accessibility-monitoring" },
  GUEST_APP: { category: "APP", approval: 0, workflow: "GUEST_APP_V1", sort: 26, slug: "guest-app" }
};
const BUNDLE_SORT = { BUNDLE_STARTER: 10, BUNDLE_GROWTH: 11, BUNDLE_PRO: 12 };
const NEW_SETUPS = {
  WEBSITE_PACKAGE: { category: "WEBSITE", approval: 1, workflow: "WEBSITE_PACKAGE_V1", sort: 30, slug: "website-package" },
  GUEST_APP_SETUP: { category: "APP", approval: 1, workflow: "GUEST_APP_SETUP_V1", sort: 31, slug: "guest-app-setup" }
};

const q = (value) => value === null || value === undefined ? "NULL" : typeof value === "number" ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const offerId = (code) => `offer_${code.toLowerCase()}`;
const lines = [
  "-- Stage 3 (Oct 25, 2026): subscription catalog. Generated by scripts/build-catalog-migration.mjs from subscription-catalog.json.",
  "-- Additive only. Every new offer is is_public = 0: nothing here is on sale until its producer passes its stage exit",
  "-- (automation rule); stage 9 flips is_public per product. Sandbox checkout can buy them; live checkout cannot.",
  `-- Stripe account ${catalog.stripe_account}.`
];

function offerRow(code, name, meta, billingType, defaultWorkflow, description) {
  lines.push(`INSERT INTO offers (id, created_at, updated_at, code, name, category, status, billing_type, fulfillment_type, requires_approval, requires_assets, default_workflow_key, public_slug, description, sort_order, is_public, is_featured, cta_text) VALUES (${[
    offerId(code), CREATED, CREATED, code, name, meta.category, "ACTIVE", billingType, "DIGITAL", meta.approval, 0, defaultWorkflow, meta.slug, description, meta.sort, 0, 0, "Get Started"
  ].map(q).join(", ")});`);
}

function versionRow(code, version, interval, entry, product, scope) {
  lines.push(`INSERT INTO offer_versions (id, offer_id, version_number, created_at, effective_from, status, price_cents, currency, billing_interval, scope_json, stripe_price_id, stripe_product_id) VALUES (${[
    `offerv${version}_${code.toLowerCase()}`, offerId(code), version, CREATED, CREATED, "ACTIVE", entry.amount, "USD", interval, JSON.stringify(scope), entry.price, product
  ].map(q).join(", ")});`);
}

// One offer per plan and bundle; version 1 bills monthly, version 2 annually (both ACTIVE, chosen by interval).
for (const [code, plan] of Object.entries(catalog.subscriptions)) {
  const meta = PLAN_META[code];
  if (!meta) throw new Error(`No metadata for plan ${code}`);
  offerRow(code, plan.name, meta, "RECURRING", meta.workflow, `${plan.name} monthly plan`);
  const scope = { kind: "PLAN", plan: code, includes: [code], ...(plan.requires_setup ? { requires_setup: plan.requires_setup } : {}) };
  versionRow(code, 1, "MONTH", plan.monthly, plan.product, scope);
  versionRow(code, 2, "YEAR", plan.annual, plan.product, scope);
}
for (const [code, bundle] of Object.entries(catalog.bundles)) {
  for (const included of bundle.includes) if (!catalog.subscriptions[included]) throw new Error(`${code} includes unknown plan ${included}`);
  const meta = { category: "CARE_PLAN", approval: 0, sort: BUNDLE_SORT[code], slug: code.toLowerCase().replace("bundle_", "") + "-plan" };
  offerRow(code, bundle.name, meta, "RECURRING", "SUBSCRIPTION_BUNDLE", `${bundle.name}: ${bundle.includes.map((p) => catalog.subscriptions[p].name).join(", ")}`);
  const scope = { kind: "BUNDLE", plan: code, includes: bundle.includes };
  versionRow(code, 1, "MONTH", bundle.monthly, bundle.product, scope);
  versionRow(code, 2, "YEAR", bundle.annual, bundle.product, scope);
}
for (const [code, meta] of Object.entries(NEW_SETUPS)) {
  const setup = catalog.one_time[code];
  offerRow(code, setup.name, meta, "ONE_TIME", meta.workflow, `${setup.name} (one-time setup)`);
  versionRow(code, 1, null, { amount: setup.amount, price: setup.price }, setup.product,
    { kind: "SETUP", setup: code, ...(setup.includes_trial ? { includes_trial: setup.includes_trial } : {}) });
}

// Producers are built in stages 5-8. Until then a period job waits at PRODUCE, which the runner does not pick up.
const workflows = [...Object.values(PLAN_META).map((m) => m.workflow), ...Object.values(NEW_SETUPS).map((m) => m.workflow)];
for (const key of workflows) {
  lines.push(`INSERT INTO workflow_definitions (id, workflow_key, version, status, steps_json, created_at, updated_at) VALUES (${[
    `wd_${key.toLowerCase()}`, key, 1, "ACTIVE", JSON.stringify([{ key: "PRODUCE", order: 10 }, { key: "DELIVER", order: 20 }]), CREATED, CREATED
  ].map(q).join(", ")});`);
}

writeFileSync(new URL("migrations/0001_subscription_catalog.sql", here), lines.join("\n") + "\n");
console.log(`Wrote ${lines.length - 4} statements`);
